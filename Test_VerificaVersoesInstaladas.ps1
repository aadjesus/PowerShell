function Get-ValorArtefato {
    param(
        [string]$nome,
        [string]$sufixo
    )

    $nome_Artefato = '';
    try {
        $nome          = ($nome -replace "\.", "_").ToUpper()
        $nome_Artefato = "RELEASE_ARTIFACTS_$($nome)_$($sufixo.ToUpper())"
        $retorno       = (Get-item env:$nome_Artefato).Value

        return $retorno
     } catch {
         Write-ErroExit "Artefato não encontrado para: $nome e $sufixo" -complemento $_
     }
}


